"""
This file will handle the trace files generated by trtexec
retuns communication_overlap,
gpu_overlap,
gpu_idle 
etc in micro-second format
"""
import json
import os
from typing import List, Dict, Any
from .util import *
import math

class Time:
    def __init__(self,trace_path: str,
                     timing_info: bool = False,
                    delete_time_details: bool = True
                 
                ):
        self.trace_path = trace_path 
        self.obj = load_json(trace_path)

        self.obj_len = len(self.obj)
        self.overlap_count = 0
        self.idle_count = 0
        self.communication_count = 0
        self.compute_count = 0
        self.inference_start_time = None
        self.inference_end_time = None
        self.overlap = None
        self.delete_details = delete_time_details
        self.len_overlap = None

        if timing_info:
            self.calculate_util()
        if self.delete_details:
            self.overlap = []
    # @requires_existing_path
    # @staticmethod
    # def load_json(file_path) -> List[Dict[str, Any]]:
    #     with open(file_path,"r") as file:
    #         data = json.load(file)
    #         return data
    
    def get_property_value(self,index: int, event: str) -> Any:
        return self.obj[index][event]
    
    def set_inference_time_util(self,) -> None:
        import sys
        max_val = -1
        min_val = sys.maxsize
        for _time in self.obj:
            try:
                max_val = max(max(_time["startH2dMs"],_time["endH2dMs"]), max_val)
                max_val = max(max_val, max(_time["startComputeMs"], _time["endComputeMs"]))
                max_val = max(max_val, max(_time["startD2hMs"], _time["endD2hMs"]))

                min_val = min(min(_time["startH2dMs"],_time["endH2dMs"]), min_val)
                min_val = min(min_val, min(_time["startComputeMs"], _time["endComputeMs"]))
                min_val = min(min_val, min(_time["startD2hMs"], _time["endD2hMs"]))
            except Exception as err:
                print(f"Exception if max of some time values: {err}")
                print("Discarding that rows of values...")
        self.inference_start_time = min_val
        self.inference_end_time = max_val
        # return max_val - min_val
    
    def set_inference_times(self,) -> None:
        for _time in self.obj:
            for item in _time:
                # print(_time[item])
                if isinstance(_time[item], int) or isinstance(_time[item], float):
                    _time[item] = math.ceil(_time[item]*1e3)
        self.set_inference_time_util()
    
    def overlap_util(self,):
        array_size = self.inference_end_time - self.inference_start_time
        min_time = self.get_property_value(0,"startH2dMs")
        # print(min_time)
        self.overlap = [[]for i in range(array_size+2)]
        for _time in self.obj:
            for i in range(_time["startH2dMs"],_time["endH2dMs"]+1):
                self.overlap[i-min_time].append(1)
            for i in range(_time["startD2hMs"],_time["endD2hMs"]+1):
                try:
                    self.overlap[i-min_time].append(1)
                except Exception as err:
                    print(f"Time: {i}, min_time: {min_time}, array_size: {array_size+1}")
            for i in range(_time["startComputeMs"],_time["endComputeMs"]+1):
                self.overlap[i-min_time].append(2)
    
    def calculate_util(self):
        self.set_inference_times()
        self.overlap_util()
        for item in self.overlap:
            self.overlap_count += (1 in item) and (2 in item)
            self.idle_count += (len(item)==0)
            self.communication_count += (1 in item)
            self.compute_count += (2 in item)
        self.len_overlap = len(self.overlap)
    
    @property
    def get_utilization_stats(self) -> Dict[str, int]:
        return {
            "communication_overlap_time": self.overlap_count / self.communication_count,
            "gpu_idle_time": self.idle_count / self.len_overlap,
            "communication_time": self.communication_count / self.len_overlap,
            "compute_time": self.compute_count / self.len_overlap
        }
    
    @property
    def get_inference_start_time(self,):
        return self.inference_start_time
    
    @property
    def get_inference_end_time(self,):
        return self.inference_end_time
    
    @property
    def get_communication_overlap(self,):
        return self.overlap_count / self.communication_count
    
    @property
    def get_gpu_idle_time(self,):
        return self.idle_count / self.len_overlap
    
    @property
    def get_communication_time(self,):
        return self.communication_count / self.len_overlap
    
    @property
    def get_gpu_commute_time(self,):
        return self.compute_count / self.len_overlap

    @property
    def get_throughput(self,):
        # the self.inference_start_time and self.inference_end_time is in us
        # the function will return the output in seconds
        # the throughput(in s) = total_thoughput *1e6 / time_interval between start and end_inference
        return self.obj_len * 1e6/ (self.inference_end_time - self.inference_start_time)
    @property
    def get_total_query(self,):
        return self.obj_len
    
def throughput(trace_path, total=False):
    # create the object
    if total:
        return total_query(trace_path=trace_path)
    obj = Time(trace_path)
    obj.set_inference_times()
    return obj.get_throughput

def total_query(trace_path):
    # create the object
    obj = Time(trace_path)
    return obj.get_total_query